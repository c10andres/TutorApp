/**
 * Genera respuestas adicionales para completar las 150
 * En producción, estas deberían venir de un archivo CSV o base de datos
 */
export function generateRemainingResponses(): SurveyResponse[] {
  const roles: SurveyResponse['Q2_Rol'][] = ['Estudiante', 'Tutor', 'Padre/Madre', 'Otro'];
  const frecuencias: SurveyResponse['Q1_FrecuenciaUso'][] = [
    'Todos los días',
    'Varias veces a la semana',
    'Una vez a la semana',
    'Varias veces al mes',
    'Rara vez',
    'Esta es la primera vez',
  ];
  const facilidades: SurveyResponse['Q3_NavegacionFacil'][] = [
    'Muy fácil',
    'Fácil',
    'Ni fácil ni difícil',
    'Difícil',
    'Muy difícil',
  ];
  const velocidades: SurveyResponse['Q5_Velocidad'][] = [
    'Muy rápida',
    'Rápida',
    'Adecuada',
    'Lenta',
    'Muy lenta',
  ];

  const responses: SurveyResponse[] = [];
  
  // Generar respuestas con distribución realista (60-75% positivas)
  for (let i = surveyResponses.length; i < 150; i++) {
    const isPositive = Math.random() < 0.7; // 70% positivas
    const role = roles[Math.floor(Math.random() * roles.length)];
    
    responses.push({
      Q1_FrecuenciaUso: frecuencias[Math.floor(Math.random() * frecuencias.length)],
      Q2_Rol: role,
      Q3_NavegacionFacil: isPositive 
        ? (Math.random() < 0.5 ? 'Muy fácil' : 'Fácil')
        : (Math.random() < 0.5 ? 'Difícil' : 'Muy difícil'),
      Q4_EncontrarLoBuscado: isPositive
        ? (Math.random() < 0.6 ? 'Siempre' : 'Casi siempre')
        : (Math.random() < 0.5 ? 'A veces' : 'Rara vez'),
      Q5_Velocidad: isPositive
        ? (Math.random() < 0.5 ? 'Muy rápida' : 'Rápida')
        : (Math.random() < 0.5 ? 'Lenta' : 'Muy lenta'),
      Q6_Estetica: isPositive
        ? (Math.random() < 0.5 ? 'Muy atractiva' : 'Atractiva')
        : 'Neutral',
      Q7_ColoresTipografia: isPositive
        ? (Math.random() < 0.5 ? 'Excelente' : 'Buena')
        : 'Neutral',
      Q8_Responsive: isPositive
        ? (Math.random() < 0.5 ? 'Muy buena' : 'Buena')
        : 'Regular',
      Q9_BusquedaTutores: role === 'Tutor' && Math.random() < 0.3
        ? 'No he usado la búsqueda'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy fácil' : 'Fácil')
        : 'Regular',
      Q10_FiltrosUtiles: Math.random() < 0.2
        ? 'No he usado los filtros'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy útiles' : 'Útiles')
        : 'Neutral',
      Q11_ClaridadPerfilTutor: Math.random() < 0.1
        ? 'No he visto perfiles de tutor'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy clara' : 'Clara')
        : 'Neutral',
      Q12_ChatExperiencia: Math.random() < 0.15
        ? 'No he usado el chat'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy buena' : 'Buena')
        : 'Neutral',
      Q13_SolicitudClara: Math.random() < 0.2
        ? 'No he realizado solicitudes'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy clara' : 'Clara')
        : 'Neutral',
      Q14_PagosAdecuados: Math.random() < 0.25
        ? 'No he realizado pagos'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy de acuerdo' : 'De acuerdo')
        : 'Neutral',
      Q15_IAUtilidad: Math.random() < 0.3
        ? 'No he utilizado la IA'
        : isPositive
        ? (Math.random() < 0.5 ? 'Muy útil' : 'Útil')
        : 'Neutral',
      Q16_Observaciones: generateObservation(isPositive),
    });
  }

  return responses;
}

function generateObservation(isPositive: boolean): string {
  const positive = [
    'La aplicación es muy intuitiva y fácil de usar.',
    'Excelente experiencia, todo funciona perfectamente.',
    'Me encanta la interfaz y la rapidez de la app.',
    'Muy útil para encontrar tutores de calidad.',
    'La funcionalidad de chat es excelente.',
  ];
  
  const negative = [
    'La app a veces va lenta y se cierra inesperadamente.',
    'La navegación podría ser más clara.',
    'Algunas funciones no funcionan como esperaba.',
    'Necesita mejoras en el rendimiento.',
  ];
  
  const mixed = [
    'En general está bien, pero hay algunos aspectos que mejorar.',
    'La app es buena pero a veces presenta errores.',
    'Funciona bien la mayoría del tiempo.',
  ];

  if (isPositive) {
    return Math.random() < 0.7 ? positive[Math.floor(Math.random() * positive.length)] : mixed[Math.floor(Math.random() * mixed.length)];
  } else {
    return Math.random() < 0.5 ? negative[Math.floor(Math.random() * negative.length)] : mixed[Math.floor(Math.random() * mixed.length)];
  }
}

